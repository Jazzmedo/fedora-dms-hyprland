				quattro_focus_direction("u")
			end,
		},
		{
			direction = "down",
			action = function()
				quattro_focus_direction("d")
			end,
		},
	}) do
		hyprgrass_swipe(3, gesture.direction, gesture.action)
	end

	for _, gesture in ipairs({
		{
			direction = "left",
			action = function()
				quattro_move_direction("l")
			end,
		},
		{
			direction = "right",
