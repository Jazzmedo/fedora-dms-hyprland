-- Pin each range to its monitor.  Hyprland merges workspace rules per selector
-- and only overwrites fields that are actually set, so the layout rules emitted
-- by quattro_apply_workspace_layout below do not clear this binding.  When DP-2
-- is unplugged, Hyprland falls back to whichever monitor is live.
for id = 1, QUATTRO_WORKSPACES_PER_MONITOR * math.max(1, #monitors.order) do
	local monitor = quattro_monitor_for_workspace(id)
	if monitor then
		hl.workspace_rule({ workspace = tostring(id), monitor = monitor })
	end
end

