-- Hyprland configuration (Lua) — https://wiki.hypr.land/Configuring/Start/

hl.config({ autogenerated = false })

-- KDE/Qt integration used by the Niri session. These must be set by the
-- compositor before DMS or application launchers start their children.
-- DMS writes its live palette to qt6ct. Routing Qt through KDE here made
-- Dolphin cache a different palette from the one DMS was updating.
hl.env("QT_QPA_PLATFORMTHEME", "qt6ct")
hl.env("QT_QPA_PLATFORM", "wayland;xcb")
hl.env("QT_WAYLAND_DISABLE_WINDOWDECORATION", "1")
hl.env("QT_AUTO_SCREEN_SCALE_FACTOR", "1")
hl.env(
	"XDG_DATA_DIRS",
	"@@HOME@@/.local/share:@@HOME@@/.local/share/flatpak/exports/share:/var/lib/flatpak/exports/share:/usr/local/share:/usr/share"
)
-- xdg-desktop-portal-hyprland requires this exact value for screencasting.
-- KDE application theming is configured separately through Qt/KDE settings.
hl.env("XDG_CURRENT_DESKTOP", "Hyprland")
hl.env("XDG_MENU_PREFIX", "plasma-")
hl.env("KDE_SESSION_VERSION", "6")
hl.env("SAL_USE_VCLPLUGIN", "kf6")
hl.env("NETWORK_SETTINGS_CMD", "nm-connection-editor")
hl.env("BLUETOOTH_SETTINGS_CMD", "blueman-manager")

-- DMS_STARTUP_BEGIN
hl.on("hyprland.start", function()
	-- Keep this ordered: services must inherit the KDE environment before the
	-- application database is built or DMS launches applications.
	hl.exec_cmd(
		"dbus-update-activation-environment --systemd --all && kbuildsycoca6 --noincremental && systemctl --user start dms.service && systemctl --user restart hypr-real-mouse-focus.service"
	)
end)

-- hyprpm loads enabled plugins after Hyprland starts. Reload once afterwards
-- so the guarded Hyprgrass bindings below are registered in the same session.
hl.on("hyprland.start", function()
	hl.exec_cmd("hyprpm list >/dev/null 2>&1 && hyprpm reload -n && hyprctl reload")
end)
-- DMS_STARTUP_END

