# shellcheck shell=bash
# Deploy the Hyprland session: modules, generated DMS files, scripts, systemd
# user units, and the hyprgrass plugin.

stage_hyprland() {
  step "Hyprland"

  # Resolve @@MONITOR@@ before anything is templated. Hyprland is not running
  # yet, so read the connected outputs from DRM instead of hyprctl.
  detect_outputs
  TPL_MONITOR=${OUTPUT_NAMES[0]}
  local i
  for i in "${!OUTPUT_NAMES[@]}"; do
    info "output ${OUTPUT_NAMES[i]}: ${OUTPUT_MODES[i]} (${OUTPUT_ORIENT[i]})"
  done

  local dest="$HOME/.config/hypr"
  deploy_tree "$REPO_DIR/config/desktop/hypr" "$dest"
  run find "$dest/scripts" -maxdepth 1 -type f -exec chmod +x {} +
  ok "hypr config deployed to ~/.config/hypr"

  write_outputs_module "$dest/dms/outputs.lua"
  write_monitors_module "$dest/monitors.lua"
  write_layout_state "$dest/quattro-state.lua"
  append_gpu_env "$dest/env.lua"

  # Only the scripts this repo ships; ~/.local/bin may hold unrelated binaries
  # and blanket-chmodding it would be rude.
  local b
  for b in "$REPO_DIR"/bin/*; do
    deploy_file "$b" "$HOME/.local/bin/$(basename "$b")" 755
  done
  ok "helper scripts in ~/.local/bin"

  install_systemd_units
  install_session_entry
  install_hyprgrass
}

# Every connected output, with its preferred mode and orientation.
# /sys/class/drm names connectors as card1-eDP-1; Hyprland calls that eDP-1.
# An internal panel is listed first so it owns workspaces 1..N.
OUTPUT_NAMES=() OUTPUT_MODES=() OUTPUT_ORIENT=()

detect_outputs() {
  OUTPUT_NAMES=() OUTPUT_MODES=() OUTPUT_ORIENT=()
  local -a internal=() external=()
  local dir name mode

  local status
  for status in /sys/class/drm/card*-*/status; do
    [[ -r $status ]] || continue
    [[ $(cat "$status") == connected ]] || continue
    dir=$(dirname "$status")
    name=$(basename "$dir"); name=${name#card*-}
    read -r mode < "$dir/modes" 2>/dev/null || mode=""
    [[ $mode =~ ^[0-9]+x[0-9]+ ]] || mode="1920x1080"
    mode=${mode%%[^0-9x]*}
    # Docks and unused DisplayPort connectors can read as "connected" while
    # offering only a 640x480 fallback mode. No real display does that, and
    # treating one as a monitor would strand half the workspaces on it.
    if (( ${mode%%x*} <= 800 && ${mode##*x} <= 600 )); then
      info "ignoring $name: reports only $mode, almost certainly a phantom connector"
      continue
    fi
    if [[ $name == eDP-* || $name == LVDS-* || $name == DSI-* ]]; then
      internal+=("$name|$mode")
    else
      external+=("$name|$mode")
    fi
  done

  local entry w hi
  for entry in "${internal[@]}" "${external[@]}"; do
    name=${entry%%|*}; mode=${entry##*|}
    w=${mode%%x*}; hi=${mode##*x}
    OUTPUT_NAMES+=("$name")
    OUTPUT_MODES+=("$mode")
    # A taller-than-wide panel scrolls down its tape instead of across it.
    if (( hi > w )); then OUTPUT_ORIENT+=("portrait"); else OUTPUT_ORIENT+=("landscape"); fi
  done

  if (( ${#OUTPUT_NAMES[@]} == 0 )); then
    warn "no connected outputs found; assuming a single 1920x1080 display"
    OUTPUT_NAMES=("Virtual-1"); OUTPUT_MODES=("1920x1080"); OUTPUT_ORIENT=("landscape")
  fi
}

detect_primary_output() { detect_outputs; printf '%s' "${OUTPUT_NAMES[0]}"; }

# DMS regenerates this file, but it has to be right for the first session or
# the bar and the clock land on a monitor that does not exist.
write_outputs_module() {
  local f=$1
  backup_path "$f"
  (( DRY_RUN )) && { info "would write $f for ${OUTPUT_NAMES[*]}"; return 0; }
  {
    echo "-- Auto-generated by DMS — do not edit manually"
    echo "-- Seeded by fedora-nothing for the outputs detected at install time."
    echo
    local i x=0
    for i in "${!OUTPUT_NAMES[@]}"; do
      printf 'hl.monitor({ output = "%s", mode = "preferred", position = "%dx0", scale = 1 })\n' \
        "${OUTPUT_NAMES[i]}" "$x"
      x=$(( x + ${OUTPUT_MODES[i]%%x*} ))
    done
  } > "$f"
  ok "outputs.lua seeded for ${#OUTPUT_NAMES[@]} output(s)"
}

# The workspace-to-monitor mapping quattro.lua reads. With one display all ten
# workspaces stay on it; with two they split five and five, and a portrait
# output gets a vertically scrolling tape.
write_monitors_module() {
  local f=$1
  local count=${#OUTPUT_NAMES[@]}
  local per=$(( count > 1 ? 10 / count : 10 ))
  (( per < 1 )) && per=1
  backup_path "$f"
  (( DRY_RUN )) && { info "would write $f: $count output(s), $per workspaces each"; return 0; }
  {
    echo "-- Generated by fedora-nothing from the displays connected at install time."
    echo "-- Re-run \`install.sh --only=hyprland\` after changing your monitor setup."
    echo
    echo "QUATTRO_WORKSPACES_PER_MONITOR = $per"
    printf 'QUATTRO_MONITOR_ORDER = {'
    local i sep=" "
    for i in "${!OUTPUT_NAMES[@]}"; do printf '%s"%s"' "$sep" "${OUTPUT_NAMES[i]}"; sep=", "; done
    printf ' }\n'
    printf 'QUATTRO_MONITOR_VERTICAL = {'
    sep=" "
    for i in "${!OUTPUT_NAMES[@]}"; do
      [[ ${OUTPUT_ORIENT[i]} == portrait ]] || continue
      printf '%s["%s"] = true' "$sep" "${OUTPUT_NAMES[i]}"; sep=", "
    done
    printf ' }\n'
  } > "$f"

  # The same facts in shell form, for scripts/monitor-topology.
  {
    echo "# Generated by fedora-nothing. Sourced by scripts/monitor-topology."
    echo "QUATTRO_WORKSPACES_PER_MONITOR=$per"
    printf 'QUATTRO_MONITOR_ORDER="%s"\n' "${OUTPUT_NAMES[*]}"
    local vertical=()
    for i in "${!OUTPUT_NAMES[@]}"; do
      [[ ${OUTPUT_ORIENT[i]} == portrait ]] && vertical+=("${OUTPUT_NAMES[i]}")
    done
    printf 'QUATTRO_MONITOR_VERTICAL="%s"\n' "${vertical[*]:-}"
  } > "${f%/*}/monitors.env"

  ok "monitors.lua: $count output(s), $per workspaces each"
}

# default_layout is what SUPER+SHIFT+L toggles away from, and what a fresh
# workspace starts as.
write_layout_state() {
  local f=$1
  if [[ -f $f ]] && grep -q "default_layout = \"$HYPR_LAYOUT\"" "$f" 2>/dev/null; then
    skip "layout already $HYPR_LAYOUT"
    return 0
  fi
  backup_path "$f"
  (( DRY_RUN )) && { info "would set the default layout to $HYPR_LAYOUT"; return 0; }
  cat > "$f" <<EOF
-- Persistent state for the Quattro-style Hyprland workflow.
-- Written by fedora-nothing; SUPER+SHIFT+L and the gap bindings update it.
return {
	default_layout = "$HYPR_LAYOUT",
	workspace_layouts = {},
	gaps_in = 4,
	gaps_out = 0,
}
EOF
  ok "default layout: $HYPR_LAYOUT"
}

append_gpu_env() {
  local f=$1
  grep -q "LIBVA_DRIVER_NAME\|WLR_NO_HARDWARE_CURSORS" "$f" 2>/dev/null && { skip "GPU env already present"; return 0; }
  (( DRY_RUN )) && { info "would append $GPU_VENDOR env to $f"; return 0; }
  gpu_env_lines >> "$f"
  ok "GPU environment appended to env.lua"
}

install_systemd_units() {
  local src="$REPO_DIR/config/desktop/systemd-user"
  local dest="$HOME/.config/systemd/user"
  deploy_tree "$src" "$dest"

  # The backup committed *.target.wants/ symlinks pointing at an absolute
  # /home/hanafi. Let systemd create them instead.
  local unit
  for unit in dms.service dms-theme-wallpapers.path dms-dolphin-palette.path \
              hypr-real-mouse-focus.service; do
    [[ -f $dest/$unit ]] || { warn "unit missing: $unit"; continue; }
    run systemctl --user enable "$unit" || soft_fail "could not enable $unit"
  done
  is_selected core && [[ -f $dest/dms-kdeconnect.service ]] && \
    run systemctl --user enable dms-kdeconnect.service

  run systemctl --user daemon-reload
  ok "systemd user units enabled"
}

install_session_entry() {
  [[ -f /usr/share/wayland-sessions/hyprland.desktop ]] \
    && { skip "Hyprland session entry provided by the package"; return 0; }
  as_root tee /usr/share/wayland-sessions/hyprland.desktop >/dev/null <<'EOF'
[Desktop Entry]
Name=Hyprland
Comment=Hyprland with DankMaterialShell
Exec=Hyprland
Type=Application
DesktopNames=Hyprland
EOF
  ok "Hyprland session entry written"
}

# hyprgrass adds the touchpad gestures quattro.lua binds. A build failure must
# not take the whole install down: the config guards every hyprgrass call.
install_hyprgrass() {
  have hyprpm || { skip "hyprpm not available, skipping hyprgrass"; return 0; }
  if hyprpm list 2>/dev/null | grep -q hyprgrass; then
    skip "hyprgrass already added"
  else
    info "building hyprgrass (this compiles against the installed Hyprland)"
    run_visible hyprpm update -n || soft_fail "hyprpm update failed"
    if run_visible hyprpm add -n https://github.com/horriblename/hyprgrass; then
      run hyprpm enable -n hyprgrass || soft_fail "could not enable hyprgrass"
      ok "hyprgrass installed"
    else
      soft_fail "hyprgrass build failed; touchpad gestures will be unavailable"
    fi
  fi
}
