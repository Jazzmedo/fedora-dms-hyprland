# shellcheck shell=bash
# Deploy the Hyprland session: modules, generated DMS files, scripts, systemd
# user units, and the hyprgrass plugin.

stage_hyprland() {

  # Resolve @@MONITOR@@ before anything is templated. Hyprland is not running
  # yet, so read the connected outputs from DRM instead of hyprctl.
  detect_outputs
  TPL_MONITOR=${OUTPUT_NAMES[0]}
  local i
  for i in "${!OUTPUT_NAMES[@]}"; do
    info "Screen ${OUTPUT_NAMES[i]}: ${OUTPUT_MODES[i]}, ${OUTPUT_ORIENT[i]}"
  done

  local dest="$HOME/.config/hypr"
  deploy_tree "$REPO_DIR/config/desktop/hypr" "$dest"
  run find "$dest/scripts" -maxdepth 1 -type f -exec chmod +x {} +
  ok "Copied the window manager settings into place"

  write_outputs_module "$dest/dms/outputs.lua"
  write_monitors_module "$dest/monitors.lua"
  write_layout_state "$dest/quattro-state.lua"
  append_gpu_env "$dest/hyprland.lua"

  # Only the scripts this repo ships; ~/.local/bin may hold unrelated binaries
  # and blanket-chmodding it would be rude.
  local b
  for b in "$REPO_DIR"/bin/*; do
    deploy_file "$b" "$HOME/.local/bin/$(basename "$b")" 755
  done
  ok "Installed the small helper scripts the shortcuts use"

  install_share_picker
  install_systemd_units
  # The unit is deployed just above and points at wherever the shell's own
  # installer put the binary, so the correction belongs here rather than in the
  # stage that installs the shell, which now runs before this one.
  fix_dms_service_path
  install_session_entry
  install_hyprgrass
}

# Every connected output, with its preferred mode and orientation.
# /sys/class/drm names connectors as card1-eDP-1; Hyprland calls that eDP-1.
# An internal panel is listed first so it owns workspaces 1..N.
OUTPUT_NAMES=() OUTPUT_MODES=() OUTPUT_ORIENT=()

detect_outputs() {
  OUTPUT_NAMES=() OUTPUT_MODES=() OUTPUT_ORIENT=()
  local -a internal=() external=()
  local dir name mode

  local status
  for status in /sys/class/drm/card*-*/status; do
    [[ -r $status ]] || continue
    [[ $(cat "$status") == connected ]] || continue
    dir=$(dirname "$status")
    name=$(basename "$dir"); name=${name#card*-}
    read -r mode < "$dir/modes" 2>/dev/null || mode=""
    [[ $mode =~ ^[0-9]+x[0-9]+ ]] || mode="1920x1080"
    mode=${mode%%[^0-9x]*}
    # Docks and unused DisplayPort connectors can read as "connected" while
    # offering only a 640x480 fallback mode. No real display does that, and
    # treating one as a monitor would strand half the workspaces on it.
    if (( ${mode%%x*} <= 800 && ${mode##*x} <= 600 )); then
      info "Ignoring $name: it reports $mode, which means nothing is really plugged in"
      continue
    fi
    if [[ $name == eDP-* || $name == LVDS-* || $name == DSI-* ]]; then
      internal+=("$name|$mode")
    else
      external+=("$name|$mode")
    fi
  done

  local entry w hi
  for entry in "${internal[@]}" "${external[@]}"; do
    name=${entry%%|*}; mode=${entry##*|}
    w=${mode%%x*}; hi=${mode##*x}
    OUTPUT_NAMES+=("$name")
    OUTPUT_MODES+=("$mode")
    # A taller-than-wide panel scrolls down its tape instead of across it.
    if (( hi > w )); then OUTPUT_ORIENT+=("portrait"); else OUTPUT_ORIENT+=("landscape"); fi
  done

  if (( ${#OUTPUT_NAMES[@]} == 0 )); then
    warn "No screen detected, so a single 1920x1080 display is assumed"
    OUTPUT_NAMES=("Virtual-1"); OUTPUT_MODES=("1920x1080"); OUTPUT_ORIENT=("landscape")
  fi
}

detect_primary_output() { detect_outputs; printf '%s' "${OUTPUT_NAMES[0]}"; }

# DMS regenerates this file, but it has to be right for the first session or
# the bar and the clock land on a monitor that does not exist.
write_outputs_module() {
  local f=$1
  backup_path "$f"
  (( DRY_RUN )) && { info "Would set up screens: ${OUTPUT_NAMES[*]}"; return 0; }
  {
    echo "-- Auto-generated by DMS — do not edit manually"
    echo "-- Seeded by fedora-nothing for the outputs detected at install time."
    echo
    local i x=0
    for i in "${!OUTPUT_NAMES[@]}"; do
      printf 'hl.monitor({ output = "%s", mode = "preferred", position = "%dx0", scale = 1 })\n' \
        "${OUTPUT_NAMES[i]}" "$x"
      x=$(( x + ${OUTPUT_MODES[i]%%x*} ))
    done
  } > "$f"
  ok "Set up ${#OUTPUT_NAMES[@]} screen(s)"
}

# The workspace-to-monitor mapping hyprland.lua reads. With one display all ten
# workspaces stay on it; with two they split five and five, and a portrait
# output gets a vertically scrolling tape.
#
# This returns a table rather than setting globals. Hyprland evaluates every
# config file in its own environment, so a global assigned in one file is not
# visible in another; dofile plus a return value is the pattern quattro-state
# already uses.
write_monitors_module() {
  local f=$1
  local count=${#OUTPUT_NAMES[@]}
  local per=$(( count > 1 ? 10 / count : 10 ))
  (( per < 1 )) && per=1
  backup_path "$f"
  (( DRY_RUN )) && { info "Would give each of $count screen(s) $per workspaces"; return 0; }
  {
    echo "-- Generated by fedora-nothing from the displays connected at install time."
    echo "-- Re-run \`install.sh --only=hyprland\` after changing your monitor setup."
    echo "return {"
    echo "	per_monitor = $per,"
    printf '\torder = {'
    local i sep=" "
    for i in "${!OUTPUT_NAMES[@]}"; do printf '%s"%s"' "$sep" "${OUTPUT_NAMES[i]}"; sep=", "; done
    printf ' },\n'
    printf '\tvertical = {'
    sep=" "
    for i in "${!OUTPUT_NAMES[@]}"; do
      [[ ${OUTPUT_ORIENT[i]} == portrait ]] || continue
      printf '%s["%s"] = true' "$sep" "${OUTPUT_NAMES[i]}"; sep=", "
    done
    printf ' },\n'
    echo "}"
  } > "$f"

  # The same facts in shell form, for scripts/monitor-topology.
  {
    echo "# Generated by fedora-nothing. Sourced by scripts/monitor-topology."
    echo "QUATTRO_WORKSPACES_PER_MONITOR=$per"
    printf 'QUATTRO_MONITOR_ORDER="%s"\n' "${OUTPUT_NAMES[*]}"
    local vertical=()
    for i in "${!OUTPUT_NAMES[@]}"; do
      [[ ${OUTPUT_ORIENT[i]} == portrait ]] && vertical+=("${OUTPUT_NAMES[i]}")
    done
    printf 'QUATTRO_MONITOR_VERTICAL="%s"\n' "${vertical[*]:-}"
  } > "${f%/*}/monitors.env"

  ok "Gave each of the $count screen(s) $per workspaces"
}

# default_layout is what SUPER+SHIFT+L toggles away from, and what a fresh
# workspace starts as.
write_layout_state() {
  local f=$1
  if [[ -f $f ]] && grep -q "default_layout = \"$HYPR_LAYOUT\"" "$f" 2>/dev/null; then
    skip "Windows already arrange themselves the $HYPR_LAYOUT way"
    return 0
  fi
  backup_path "$f"
  (( DRY_RUN )) && { info "Would arrange windows the $HYPR_LAYOUT way"; return 0; }
  cat > "$f" <<EOF
-- Persistent state for the Quattro-style Hyprland workflow.
-- Written by fedora-nothing; SUPER+SHIFT+L and the gap bindings update it.
return {
	default_layout = "$HYPR_LAYOUT",
	workspace_layouts = {},
	gaps_in = 4,
	gaps_out = 0,
}
EOF
  ok "Windows will arrange themselves the $HYPR_LAYOUT way"
}

# The graphics-driver environment goes into hyprland.lua at its marker, beside
# the other hl.env calls, so it is set before the session starts anything.
append_gpu_env() {
  local f=$1
  local marker="-- FEDORA_NOTHING_GPU_ENV"
  if grep -q "LIBVA_DRIVER_NAME\|WLR_NO_HARDWARE_CURSORS" "$f" 2>/dev/null; then
    skip "The graphics settings are already in the config"
    return 0
  fi
  (( DRY_RUN )) && { info "Would add the $GPU_VENDOR graphics settings"; return 0; }
  grep -q -- "$marker" "$f" || { soft_fail "Could not add the graphics settings" \
       "The marker they get inserted at is missing from hyprland.lua." \
       "Restore the file from assets, then: ./install.sh --only=hyprland"; return 0; }

  local block; block=$(mktemp)
  gpu_env_lines > "$block"
  awk -v marker="$marker" -v blockfile="$block" '
    { print }
    !done && index($0, marker) {
      while ((getline line < blockfile) > 0) print line
      close(blockfile)
      done = 1
    }
  ' "$f" > "$f.new" && mv "$f.new" "$f"
  rm -f "$block"
  ok "Added the $GPU_VENDOR graphics settings"
}

# Units this repository used to install. deploy_tree only ever adds files, so
# without this the old Dolphin-only watcher stays enabled beside the new one
# and both broadcast a palette change, which repaints every window twice.
retire_old_units() {
  local dest="$HOME/.config/systemd/user" unit
  for unit in dms-dolphin-palette.path dms-dolphin-palette.service \
              hypr-real-mouse-focus.service; do
    [[ -e $dest/$unit ]] || continue
    run systemctl --user disable --now "$unit" 2>/dev/null || true
    run rm -f "$dest/$unit" "$dest"/*.wants/"$unit"
    ok "Removed the old $unit"
  done
  run rm -f "$HOME/.config/hypr/scripts/guard-dolphin-palette"
  # The hover-focus watcher polled top-level clients only, so a right-click
  # menu taller than its window lost focus to the window underneath and
  # closed. Hyprland does this natively with follow_mouse = 1 plus
  # mouse_refocus = false, both set in config/desktop/hypr/hyprland.lua.
  run rm -f "$HOME/.config/hypr/scripts/focus-follows-real-mouse"
  return 0
}

install_systemd_units() {
  local src="$REPO_DIR/config/desktop/systemd-user"
  local dest="$HOME/.config/systemd/user"
  deploy_tree "$src" "$dest"
  retire_old_units

  # The backup committed *.target.wants/ symlinks pointing at an absolute
  # /home/hanafi. Let systemd create them instead.
  local unit
  for unit in dms.service dms-theme-wallpapers.path dms-theme-reload.path; do
    [[ -f $dest/$unit ]] || { warn "A startup file is missing: $unit"; continue; }
    enable_user_unit "$unit" && record unit-user "$unit" \
      || soft_fail "Could not set $unit to start automatically" "" "systemctl --user enable $unit"
  done
  is_selected core && [[ -f $dest/dms-kdeconnect.service ]] && \
    enable_user_unit dms-kdeconnect.service && record unit-user dms-kdeconnect.service

  user_daemon_reload
  ok "The desktop will now start these services when you log in"
}

install_session_entry() {
  [[ -f /usr/share/wayland-sessions/hyprland.desktop ]] \
    && { skip "Hyprland already appears as a choice on the login screen"; return 0; }
  record file /usr/share/wayland-sessions/hyprland.desktop
  as_root tee /usr/share/wayland-sessions/hyprland.desktop >/dev/null <<'EOF'
[Desktop Entry]
Name=Hyprland
Comment=Hyprland with DankMaterialShell
Exec=Hyprland
Type=Application
DesktopNames=Hyprland
EOF
  ok "Hyprland now appears as a choice on the login screen"
}

# hyprgrass adds the touchpad gestures quattro.lua binds. A build failure must
# not take the whole install down: the config guards every hyprgrass call.
# The screen-share source chooser. xdg-desktop-portal-hyprland ships a Qt
# Widgets picker; xdph.conf points it at the wrapper in bin/ instead, and that
# wrapper execs this one. Without the payload the wrapper has nothing to run,
# the portal's custom picker fails, and screen sharing offers no window list at
# all, which is why it is deployed here rather than left to the shell's own
# installer.
install_share_picker() {
  local src="$REPO_DIR/assets/share-picker"
  [[ -d $src ]] || return 0
  deploy_tree "$src" "$HOME/.local/share/quickshell-share-picker"
  ok "Installed the screen-share source chooser"
}

install_hyprgrass() {
  have hyprpm || { skip "Touchpad gestures need a tool that is not installed"; return 0; }

  # hyprpm asks the running compositor which version to build against. From a
  # text console there is none, so it spends a minute or two cloning Hyprland
  # and then fails with "HYPRLAND_INSTANCE_SIGNATURE was not set". Skip it here
  # and say when to run it instead of burning the time on a certain failure.
  if [[ -z ${HYPRLAND_INSTANCE_SIGNATURE:-} ]]; then
    skip "Touchpad gestures are set up from inside the desktop, not from here"
    info "After you log in, run: hyprpm update && hyprpm add https://github.com/horriblename/hyprgrass && hyprpm enable hyprgrass"
    return 0
  fi

  if hyprpm list 2>/dev/null | grep -q hyprgrass; then
    skip "Touchpad gestures are already set up"
  else
    # hyprpm compiles plugins against the exact Hyprland it finds, and refuses
    # to build when the running headers do not match the packaged ones. On a
    # COPR build that mismatch is common, so this stays optional: the config
    # guards every hyprgrass call and the desktop is fine without it.
    info "Building the touchpad gesture add-on. This takes a minute or two."
    if ! run_visible hyprpm update -n; then
      soft_fail "Could not prepare the touchpad gesture add-on" \
                "The build needs Hyprland's developer files, which it could not fetch." \
                "Everything else works. To retry: ./install.sh --only=hyprland"
      return 0
    fi
    if run_visible hyprpm add -n https://github.com/horriblename/hyprgrass; then
      run hyprpm enable -n hyprgrass || soft_fail "Built the touchpad gestures but could not switch them on" "" "hyprpm enable hyprgrass"
      ok "Touchpad gestures are set up"
    else
      soft_fail "The touchpad gesture add-on did not build" \
                "It compiles against your exact Hyprland version and something did not match." \
                "Everything else works. To retry: ./install.sh --only=hyprland"
    fi
  fi
}
