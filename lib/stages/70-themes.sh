# shellcheck shell=bash
# Wallpapers, the matugen pipeline, and the GTK/Qt/KDE surfaces that DMS
# recolours when the theme changes.

stage_themes() {
  install_wallpapers
  install_matugen_config
  install_toolkit_theming
}

install_wallpapers() {
  local dest="$HOME/Pictures/Wallpapers/theme-collections"
  local src="$REPO_DIR/assets/wallpapers"
  run mkdir -p "$dest"
  local set_dir name
  for set_dir in "$src"/*/; do
    name=$(basename "$set_dir")
    local have_n want_n
    want_n=$(count_files "$set_dir/horizontal")
    have_n=$(count_files "$dest/$name/horizontal")
    # Compared by count, not merely "is it non-empty": the old check meant new
    # images added to this repo never reached a machine that had the set.
    if (( have_n >= want_n )) && (( want_n > 0 )); then
      skip "The $name wallpapers are already there"
      continue
    fi
    run mkdir -p "$dest/$name/horizontal" "$dest/$name/vertical"
    record file "$dest/$name"
    run cp -a "$set_dir/horizontal/." "$dest/$name/horizontal/"
    ok "Added $want_n $name wallpapers"
  done
  # Collections of themes this repository no longer ships. A machine that
  # installed them earlier should not keep them forever.
  local gone
  for gone in catppuccin-mocha gruvbox-material; do
    [[ -e "$dest/$gone" ]] || continue
    run rm -rf "$dest/$gone"
    record file "$dest/$gone"
  done
  # The theme-sync script falls back to the horizontal image on portrait
  # outputs when a vertical set is absent, so empty vertical/ dirs are fine.
}

# spicetify is never installed by this repository; it is detected. Both places
# it can live: on PATH, and the fixed path its own installer uses.
spicetify_present() { have spicetify || [[ -x $HOME/.spicetify/spicetify ]]; }

# matugen's config is assembled from fragments so a deselected app does not
# leave a template writing into a directory that will never exist.
install_matugen_config() {
  local src="$REPO_DIR/config/theming/matugen"
  local dest="$HOME/.config/matugen"

  deploy_tree "$src/templates" "$dest/templates"
  # The foot colour template regenerates dms-colors.ini on every theme change,
  # so match its section name to the installed foot here, where it is deployed.
  foot_use_colors_dark "$dest/templates/foot-dms.ini"

  backup_path "$dest/config.toml"
  run mkdir -p "$dest"

  if (( DRY_RUN )); then
    info "Would build the colour-generator settings"
  else
    {
      printf '# Generated by fedora-nothing from config/theming/matugen/conf.d/.\n'
      printf '# Edit the fragments and re-run the installer, not this file.\n\n'
      cat "$src/conf.d/00-base.toml"
      local frag key
      for frag in "$src"/conf.d/*.toml; do
        key=$(basename "$frag" .toml)
        [[ $key == 00-base ]] && continue
        case $key in
          # Guarded on the profile existing, not merely on Zen being selected:
          # detect_zen_profile falls back to ~/.zen/default, and matugen would
          # create that directory to write the output into it, leaving Zen a
          # brand-new empty profile to open instead of the real one.
          zen)  { is_selected zen && [[ -d $(detect_zen_profile) ]]; } || continue ;;
          # The same guard, for the same reason: no profile, no fragment.
          firefox|librewolf) { is_selected "$key" && bp_profile "$key" >/dev/null; } || continue ;;
          # Theming only: never emitted on a machine that has no spicetify.
          spicetify) { is_selected spicetify && spicetify_present; } || continue ;;
          foot) is_selected term_foot || continue ;;
          *)    is_selected "$key"    || continue ;;
        esac
        printf '\n'
        cat "$frag"
      done
    } > "$dest/config.toml"
    TPL_ZEN_PROFILE=$(detect_zen_profile)
    # matugen makes an output file's parent, but only once the profile itself
    # exists. Guarded, because detect_zen_profile falls back to ~/.zen/default
    # and creating that would give Zen an empty profile to open.
    [[ -d $TPL_ZEN_PROFILE ]] && run mkdir -p "$TPL_ZEN_PROFILE/chrome"
    apply_template "$dest/config.toml"
    local k profile
    for k in firefox librewolf; do
      profile=$(bp_profile "$k") || continue
      run mkdir -p "$profile/chrome"
      sed -i "s|@@${k^^}_PROFILE@@|$profile|g" "$dest/config.toml"
    done
  fi
  ok "Set up the colour generator, so apps recolour when you change theme"
}

# Zen's profile directory has a random prefix, so the template path can only be
# resolved once the browser has created it.
# Zen keeps its profiles in ~/.zen when installed from its tarball and in
# ~/.config/zen when run as an AppImage. Looking in one place meant matugen
# wrote the browser theme into a directory that did not exist, and the browser
# was never themed at all.
# Prints the whole profile directory, not just its name: Zen keeps profiles in
# ~/.zen when installed from its tarball and in ~/.config/zen when run as an
# AppImage. Looking in one place meant matugen wrote the browser theme into a
# directory that did not exist, so the browser was never themed at all.
detect_zen_profile() {
  local root d rel
  for root in "$HOME/.zen" "$HOME/.config/zen"; do
    [[ -d $root ]] || continue
    # installs.ini names the profile Zen actually launches (its locked
    # per-install default). profiles.ini can flag a different one Default=1 that
    # Zen ignores, and the *.Default* glob returns whichever sorts first, so
    # without this the theme lands in a profile the browser never opens.
    if [[ -f "$root/installs.ini" ]]; then
      rel=$(sed -n 's/^Default=//p' "$root/installs.ini" | head -1)
      [[ -n $rel && -d "$root/$rel" ]] && { printf '%s' "$root/$rel"; return; }
    fi
    for d in "$root"/*.Default* "$root"/*default*; do
      [[ -d $d ]] && { printf '%s' "$d"; return; }
    done
  done
  printf '%s' "$HOME/.zen/default"
}

install_toolkit_theming() {
  local t="$REPO_DIR/config/theming"
  deploy_tree "$t/gtk-3.0" "$HOME/.config/gtk-3.0"
  deploy_tree "$t/gtk-4.0" "$HOME/.config/gtk-4.0"
  deploy_tree "$t/qt5ct"   "$HOME/.config/qt5ct"
  deploy_tree "$t/qt6ct"   "$HOME/.config/qt6ct"
  deploy_file "$t/gtkrc-2.0" "$HOME/.gtkrc-2.0"
  deploy_tree "$t/kde-color-schemes" "$HOME/.local/share/color-schemes"
  # Colour schemes of themes this repository no longer ships; a deployed copy
  # from an earlier run would otherwise sit in the picker forever.
  local dead_scheme
  for dead_scheme in CatppuccinMocha CatppuccinMochaSaphhire InfinityDarkColor \
                     InfinityLightColor Sweet-Mars SweetAmbarBlue; do
    [[ -e "$HOME/.local/share/color-schemes/$dead_scheme.colors" ]] || continue
    run rm -f "$HOME/.local/share/color-schemes/$dead_scheme.colors"
    record file "$HOME/.local/share/color-schemes/$dead_scheme.colors"
  done

  # The colour files themselves are seeded once and owned by the desktop shell
  # from then on. Copying the captured ones over the generated ones on every
  # run is what used to reset every open window to the palette of the machine
  # this repository was captured from.
  deploy_seed "$t/gtk-3.0/seed/dank-colors.css" "$HOME/.config/gtk-3.0/dank-colors.css"
  deploy_seed "$t/gtk-4.0/seed/dank-colors.css" "$HOME/.config/gtk-4.0/dank-colors.css"
  deploy_seed "$t/qt5ct/seed/matugen.conf" "$HOME/.config/qt5ct/colors/matugen.conf"
  deploy_seed "$t/qt6ct/seed/matugen.conf" "$HOME/.config/qt6ct/colors/matugen.conf"
  local scheme
  for scheme in "$t"/kde-color-schemes/seed/*.colors; do
    [[ -f $scheme ]] || continue
    deploy_seed "$scheme" "$HOME/.local/share/color-schemes/$(basename "$scheme")"
  done
  ok "Put the colour settings in place for every kind of app"

  # gtk.css must point at the file the shell rewrites, or GTK apps keep the
  # palette they were built with. The link is made here rather than shipped:
  # a symlink in the repository would dangle, since its target is a seed file
  # that is deployed separately.
  run ln -sfn dank-colors.css "$HOME/.config/gtk-3.0/gtk.css"

  # Both settings.ini files ask for adw-gtk3-dark. Without it GTK apps fall
  # back to Adwaita and DMS refuses to refresh the GTK theme at all, logging
  # "Skipping gtk-theme refresh" and leaving every GTK app off-palette.
  if [[ -d /usr/share/themes/adw-gtk3-dark ]]; then
    have gsettings && run gsettings set org.gnome.desktop.interface gtk-theme "adw-gtk3-dark"
  else
    soft_fail "The GTK theme is missing, so some apps will not follow your colours" \
              "adw-gtk3-dark is what those apps read their colours from." \
              "sudo dnf install adw-gtk3-theme"
  fi

  # GTK reads the font from gsettings, not only from settings.ini.
  if have gsettings; then
    run gsettings set org.gnome.desktop.interface font-name          "Ndot 57 11"
    run gsettings set org.gnome.desktop.interface monospace-font-name "JetBrainsMono Nerd Font Mono 10"
    run gsettings set org.gnome.desktop.interface cursor-theme        "Afterglow-cursors"
    run gsettings set org.gnome.desktop.interface cursor-size          24
    run gsettings set org.gnome.desktop.interface icon-theme           "Cawnonical Mono-Glyph Icon Suite (White)"
    run gsettings set org.gnome.desktop.interface color-scheme         "prefer-dark"
    ok "Set the font, the mouse cursor, the icons and dark mode"
  fi

  seed_kde_palette
  # Not `is_selected ... && deploy_file`: with Dolphin deselected the && list
  # fails, and as the last statement it becomes this function's return value —
  # which set -e treats as the stage crashing. It took down every run that
  # picked Thunar only, with nothing in the log pointing here.
  if is_selected filemgr_dolphin; then
    deploy_file "$REPO_DIR/config/apps/dolphinrc" "$HOME/.config/dolphinrc"
  fi
}

# Dolphin is a KDE application, so it paints itself from the [Colors:*] blocks
# inside kdeglobals rather than from the Qt palette qt6ct hands it. Naming a
# scheme in ColorScheme= is not enough: on Plasma it is plasma-apply-colorscheme
# that copies the scheme's sections into kdeglobals, and under Hyprland nothing
# does. Without those sections Dolphin renders in stock Breeze light however
# dark the rest of the desktop is, which is exactly the mismatch this fixes.
seed_kde_palette() {
  local scheme="$HOME/.local/share/color-schemes/DankMatugenDark.colors"
  local kg="$HOME/.config/kdeglobals"

  ini_set "$kg" "Icons" "Theme"       "Cawnonical Mono-Glyph Icon Suite (White)"
  ini_set "$kg" "KDE"   "widgetStyle" "Fusion"

  if [[ ! -f $scheme ]]; then
    soft_fail "The colour scheme file is missing, so the file manager stays light" \
                "It should have been copied in a moment ago." \
                "./install.sh --only=themes"
    return 0
  fi
  if (( DRY_RUN )); then
    info "Would give the file manager the dark colours"
    return 0
  fi

  backup_path "$kg"
  if python3 "$REPO_DIR/lib/kde_palette.py" "$scheme" "$kg"; then
    ok "The file manager now uses your desktop colours"
  else
    soft_fail "Could not give the file manager your colours" "" "./install.sh --only=themes"
  fi

  # KDE caches the palette per application; without this Dolphin keeps the
  # colours it started with until the next login. Never fatal: the cache
  # rebuild has been known to fail on a machine without a running session,
  # and losing the stage to it costs every step that follows.
  if have kbuildsycoca6; then
    run kbuildsycoca6 --noincremental \
      || warn "KDE's app cache did not refresh; the new colours arrive at the next login"
  fi
  return 0
}
