#!/usr/bin/env bash
# Set up one monitor at a time: its rotation, the direction new windows open
# on its tape, and the direction its workspaces switch. Everything is chosen on
# screen, like the installer; the result is applied to the running Hyprland
# session and kept for the next one.
#
#   rotation    ~/.config/hypr/dms/outputs.lua (DMS keeps it from then on)
#   windows     ~/.config/hypr/monitors.lua, read by hyprland.lua
#   workspaces  ~/.config/hypr/monitors.env, read by scripts/monitor-workspace
#
# The theme wallpaper follows by itself: each monitor gets the image that
# matches its shape once it is rotated.
set -euo pipefail

REPO_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
DRY_RUN=0 ASSUME_YES=0 NO_BACKUP=0 PRESET="" LOG_FILE="" MANIFEST_FILE=""

# shellcheck source=lib/common.sh
source "$REPO_DIR/lib/common.sh"
# shellcheck source=lib/progress.sh
source "$REPO_DIR/lib/progress.sh"
# shellcheck source=lib/components.sh
source "$REPO_DIR/lib/components.sh"
# shellcheck source=lib/ui.sh
source "$REPO_DIR/lib/ui.sh"
# shellcheck source=lib/stages/50-hyprland.sh
source "$REPO_DIR/lib/stages/50-hyprland.sh"
set_colors 2>/dev/null || true

[[ -t 0 && -t 1 ]] || die "Run this in a terminal" "Every choice is made on screen."
[[ -n ${HYPRLAND_INSTANCE_SIGNATURE:-} ]] && have hyprctl \
  || die "This only works inside a Hyprland session"
have jq || die "jq is missing" "" "sudo dnf install jq"

HYPR="$HOME/.config/hypr"
OUTPUTS="$HYPR/dms/outputs.lua"
ROT_NAMES=("Landscape" "Portrait" "Landscape, upside down" "Portrait, flipped")

# The first ticked key of a radio group, without its prefix.
picked_in() {
  local k
  for k in $(group_members "$1"); do is_selected "$k" && { printf '%s' "${k#*_}"; return; }; done
}

# What monitors.env says about one output: its window direction and whether
# its workspaces slide sideways. Older files only know "vertical".
saved_layout() {   # name -> "direction slide"
  local name=$1 dirs="" side="" vert="" set_side=0 e dir="" slide
  if [[ -r $HYPR/monitors.env ]]; then
    dirs=$(sed -n 's/^QUATTRO_MONITOR_DIRECTIONS="\(.*\)"$/\1/p' "$HYPR/monitors.env")
    vert=$(sed -n 's/^QUATTRO_MONITOR_VERTICAL="\(.*\)"$/\1/p' "$HYPR/monitors.env")
    grep -q '^QUATTRO_MONITOR_SIDEWAYS=' "$HYPR/monitors.env" && set_side=1
    side=$(sed -n 's/^QUATTRO_MONITOR_SIDEWAYS="\(.*\)"$/\1/p' "$HYPR/monitors.env")
  fi
  for e in $dirs; do [[ ${e%%:*} == "$name" ]] && dir=${e#*:}; done
  [[ -n $dir ]] || { [[ " $vert " == *" $name "* ]] && dir=down || dir=right; }
  (( set_side )) || side=$vert
  [[ " $side " == *" $name "* ]] && slide=slide || slide=slidevert
  printf '%s %s' "$dir" "$slide"
}

# Rotate one output in DMS's outputs.lua, and line the outputs up again left to
# right: a monitor that turns to portrait gets narrower, and its neighbours
# would otherwise overlap it or leave a gap. Heights stay where they were.
write_rotation() {   # name transform
  backup_path "$OUTPUTS"
  python3 - "$OUTPUTS" "$1" "$2" "$(hyprctl monitors -j)" <<'PY'
import json, re, sys
path, target, transform = sys.argv[1], sys.argv[2], int(sys.argv[3])
mons = json.loads(sys.argv[4])
try:
    lines = open(path).read().splitlines()
except OSError:
    lines = ['-- Auto-generated by DMS — do not edit manually', '']

def line_of(name):
    for i, l in enumerate(lines):
        if re.search(r'output\s*=\s*"%s"' % re.escape(name), l):
            return i
    lines.append('hl.monitor({ output = "%s", mode = "preferred", position = "0x0", scale = 1 })' % name)
    return len(lines) - 1

x = min(m['x'] for m in mons)
for m in sorted(mons, key=lambda m: m['x']):
    t = transform if m['name'] == target else m['transform']
    i = line_of(m['name'])
    l = re.sub(r',\s*transform\s*=\s*\d+', '', lines[i])
    if t:
        l = re.sub(r'\s*\}\)\s*$', ', transform = %d })' % t, l)
    l = re.sub(r'position\s*=\s*"[^"]*"', 'position = "%dx%d"' % (x, m['y']), l)
    lines[i] = l
    w, h = (m['height'], m['width']) if t % 2 else (m['width'], m['height'])
    x += round(w / (m.get('scale') or 1))
open(path, 'w').write('\n'.join(lines) + '\n')
PY
}

# Keep every other output's settings and change this one's.
write_layout() {   # name direction slide
  local order="" i
  [[ -r $HYPR/monitors.env ]] && order=$(sed -n 's/^QUATTRO_MONITOR_ORDER="\(.*\)"$/\1/p' "$HYPR/monitors.env")
  [[ -n $order ]] || order=$(hyprctl monitors -j | jq -r '[.[] | .name] | join(" ")')
  [[ " $order " == *" $1 "* ]] || order+=" $1"
  read -ra OUTPUT_NAMES <<<"$order"
  OUTPUT_DIRECTION=() OUTPUT_SLIDE=() OUTPUT_ORIENT=()
  for i in "${!OUTPUT_NAMES[@]}"; do
    [[ ${OUTPUT_NAMES[i]} == "$1" ]] && { OUTPUT_DIRECTION[i]=$2; OUTPUT_SLIDE[i]=$3; }
  done
  write_monitors_module "$HYPR/monitors.lua" >/dev/null
}

# Sets MONITOR.
pick_monitor() {
  local mons count
  mons=$(hyprctl monitors -j)
  count=$(jq length <<<"$mons")
  (( count > 0 )) || die "Hyprland reports no monitors"
  if (( count == 1 )); then MONITOR=$(jq -r '.[0].name' <<<"$mons"); return; fi

  new_list
  group mon "Which monitor"
  local i name desc
  for (( i = 0; i < count; i++ )); do
    name=$(jq -r ".[$i].name" <<<"$mons")
    desc=$(jq -r ".[$i] | \"\(.make) \(.model)\" | gsub(\"^ +| +$\"; \"\")" <<<"$mons")
    desc+=", $(jq -r ".[$i] | \"\(.width)x\(.height)\"" <<<"$mons"), ${ROT_NAMES[$(jq -r ".[$i].transform % 4" <<<"$mons")]}"
    component "mon_$i" mon off "$name" "$desc"
    [[ $(jq -r ".[$i].focused" <<<"$mons") == true ]] && select_component "mon_$i"
  done
  UI_TITLE="Monitor layout" UI_SUBTITLE="pick the monitor to set up" UI_ACCEPT="continue"
  UI_LEGEND="Space picks one" UI_RADIO_GROUPS="mon"
  ui_select_components
  i=$(picked_in mon); [[ -n $i ]] || die "No monitor was picked"
  MONITOR=$(jq -r ".[$i].name" <<<"$mons")
}

setup_monitor() {
  local name=$1 transform dir slide
  transform=$(hyprctl monitors -j | jq -r --arg n "$name" '.[] | select(.name == $n) | .transform % 4')
  read -r dir slide <<<"$(saved_layout "$name")"

  new_list
  group rot "Rotation"
  component rot_0 rot off "Landscape"              "normal"
  component rot_1 rot off "Portrait"               "turned 90°"
  component rot_2 rot off "Landscape, upside down" "turned 180°"
  component rot_3 rot off "Portrait, flipped"      "turned 270°"
  group win "New windows open"
  component win_right win off "To the right" "the tape grows across the screen"
  component win_left  win off "To the left"  "across, the other way"
  component win_down  win off "Downward"     "the tape grows down the screen; suits portrait"
  component win_up    win off "Upward"       "down, the other way"
  group ws "Workspaces switch"
  component ws_slidevert ws off "Up and down"    "like the laptop screen"
  component ws_slide     ws off "Left and right" "suits a downward tape"
  select_component "rot_$transform"; select_component "win_$dir"; select_component "ws_$slide"

  UI_TITLE="Monitor layout" UI_SUBTITLE="$name: pick one in each group" UI_ACCEPT="apply"
  UI_LEGEND="Space picks one" UI_RADIO_GROUPS="rot win ws"
  ui_select_components

  local new_t new_dir new_slide
  new_t=$(picked_in rot) new_dir=$(picked_in win) new_slide=$(picked_in ws)

  step "Applying to $name"
  if [[ $new_t != "$transform" ]]; then
    write_rotation "$name" "$new_t"
    ok "Rotation: ${ROT_NAMES[new_t]}"
  fi
  write_layout "$name" "$new_dir" "$new_slide"
  ok "New windows open $( [[ $new_dir == down || $new_dir == up ]] && echo "$new_dir"ward || echo "to the $new_dir" )"
  ok "Workspaces switch $( [[ $new_slide == slide ]] && echo "left and right" || echo "up and down" )"

  hyprctl reload >/dev/null
  sleep 1
  local errors; errors=$(hyprctl configerrors 2>/dev/null | sed '/^\s*$/d')
  [[ -z $errors ]] || warn "Hyprland reports config errors:"$'\n'"$errors"
  if systemctl --user start dms-theme-wallpapers.service 2>/dev/null; then
    ok "The theme wallpaper matches the monitor's shape"
  else
    warn "The theme wallpaper could not be refreshed (journalctl --user -u dms-theme-wallpapers)"
  fi
}

while :; do
  pick_monitor
  setup_monitor "$MONITOR"
  (( $(hyprctl monitors -j | jq length) > 1 )) || break
  printf '\n  %s?%s Set up another monitor? [y/N] ' "$C_RED" "$C_OFF"
  read -r reply
  [[ $reply == [yY]* ]] || break
done
